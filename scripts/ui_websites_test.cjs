const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  fs.mkdirSync('qa',{recursive:true});
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8001');
    await page.locator('#login-form input[name=password]').fill('website-browser-only');
    if(await page.locator('#login-form input[name=confirm]').count())await page.locator('#login-form input[name=confirm]').fill('website-browser-only');
    await page.locator('#login-form button').click();
    await page.locator('nav [data-nav=websites]').click();
    await page.getByRole('heading',{name:'网站检索',exact:true}).waitFor();
    const form=page.locator('#website-source-form');
    await form.locator('[name=name]').fill('合成测试公告网站');
    await form.locator('[name=url]').fill('https://example.com/news/');
    await form.getByRole('button',{name:'保存来源'}).click();
    await page.locator('[name=source_ids]').check();
    await page.locator('#website-search-form [name=query]').fill('供电风险');
    await page.getByRole('button',{name:'检索指定网站'}).click();
    await page.waitForURL(/websites\?task=/);
    await page.locator('[data-site-result]').first().waitFor();
    const ready=page.locator('[data-site-result]').filter({hasText:'合成测试：园区供电公告'});
    const summary=page.locator('[data-site-result]').filter({hasText:'合成测试：只有摘要'});
    assert(await summary.locator('[data-site-import]').first().isDisabled());
    assert.equal(await page.locator('[data-site-result]').count(),2);
    await ready.getByText('查看来源正文快照',{exact:true}).click();
    await ready.getByRole('button',{name:'加入知识库'}).click();
    await ready.getByText(/知识库 #/).waitFor();
    await ready.getByRole('button',{name:'加入待分析资料'}).click();
    await ready.getByText(/待分析资料 #/).waitFor();
    const task=Number(page.url().split('task=')[1]);
    const detail=await (await page.request.get('http://127.0.0.1:8001/api/websites/searches/'+task)).json();
    const item=detail.items.find(i=>i.content_status==='ready');
    assert.equal(item.documents.length,2);
    const event=item.documents.find(d=>d.kind==='event');
    const doc=await (await page.request.get('http://127.0.0.1:8001/api/documents/'+event.document_id)).json();
    assert.equal(doc.allow_external,0);
    assert.equal(doc.website_origin.url,'https://example.com/news/power');
    await ready.getByRole('button',{name:'查看入库原文'}).first().click();
    await page.getByText(/网站来源版本 #/).waitFor();
    await page.locator('#close-source').click();
    await summary.getByRole('button',{name:'忽略',exact:true}).click();
    await summary.getByText(/已忽略/).waitFor();
    await page.screenshot({path:'qa/website-search-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'qa/website-search-mobile.png',fullPage:true});
    await page.reload();
    await page.getByText(/待分析资料 #/).waitFor();
    assert.deepEqual(errors,[]);
    fs.writeFileSync('qa/website-browser-results.json',JSON.stringify({status:'passed',checks:['site configuration','queued search','source filtering','summary-only blocked','knowledge import','event import','default external authorization denied','origin snapshot trace','ignore result','reload persistence','desktop/mobile layout'],errors},null,2));
    console.log('Website browser workflow passed.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
